package com.intermarche.edge.domain.sale;

import io.quarkus.hibernate.orm.panache.PanacheEntity;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Table;

import java.time.LocalDateTime;
import java.util.List;

/**
 * A THIRD-PARTY SYSTEM whose sales the point of sale integrates
 * (BO-07-01-01): the e-commerce platform, a mobility tool.
 *
 * <p>The integration activity is administered here, system by system: what
 * kind of system it is (its {@link SalesChannel}), the point of sale its
 * sales count for, the virtual register they are booked on, whether it may
 * deposit at all, and the TOKEN it presents in {@code X-Integration-Token} —
 * one secret per system, generated by the back office, so a system is
 * recognised by what it presents and one can be cut off without touching the
 * others nor the registers' shared synchronization token.
 */
@Entity
@Table(name = "third_party_systems")
public class ThirdPartySystem extends PanacheEntity {

    /** The stable code of the system, unique (for example, SITE_WEB). */
    @Column(name = "code", unique = true, nullable = false, length = 40)
    public String code;

    /** The operator-facing label. */
    @Column(name = "label", nullable = false, length = 100)
    public String label;

    /** The kind of system: the channel its sales are booked under. */
    @Enumerated(EnumType.STRING)
    @Column(name = "channel", nullable = false, length = 16)
    public SalesChannel channel = SalesChannel.ECOMMERCE;

    /** The token the system presents, unique; regenerated by the back office. */
    @Column(name = "token", unique = true, nullable = false, length = 64)
    public String token;

    /** Whether the system may deposit its sales; deactivated, never deleted. */
    @Column(name = "active", nullable = false)
    public boolean active = true;

    /** The point of sale its sales count for, or null for this node's store. */
    @Column(name = "pdv_number", length = 20)
    public String pdvNumber;

    /** The virtual register its sales are booked on, or null for the channel's. */
    @Column(name = "terminal_id", length = 20)
    public String terminalId;

    /** When the system last deposited a sale, or null. */
    @Column(name = "last_call_at")
    public LocalDateTime lastCallAt;

    /** How many sales it deposited. */
    @Column(name = "order_count", nullable = false)
    public long orderCount;

    /**
     * Finds the system presenting a token.
     *
     * @param token the presented token, or null
     * @return the system, or null when no system holds that token
     */
    public static ThirdPartySystem findByToken(String token) {
        if (token == null || token.isBlank()) {
            return null;
        }
        return find("token", token.trim()).firstResult();
    }

    /**
     * Finds a system by its code.
     *
     * @param code the code, or null
     * @return the system, or null when unknown
     */
    public static ThirdPartySystem findByCode(String code) {
        if (code == null || code.isBlank()) {
            return null;
        }
        return find("code", code.trim()).firstResult();
    }

    /**
     * Lists every system, by code, for the back-office screen.
     *
     * @return the systems, never null
     */
    public static List<ThirdPartySystem> listAllOrdered() {
        return list("order by code");
    }
}
