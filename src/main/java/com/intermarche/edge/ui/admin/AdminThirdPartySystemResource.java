package com.intermarche.edge.ui.admin;

import com.intermarche.edge.domain.people.CrudOption;
import com.intermarche.edge.domain.sale.SalesChannel;
import com.intermarche.edge.domain.sale.ThirdPartySystem;
import com.intermarche.edge.domain.setting.Feature;
import com.intermarche.edge.domain.store.Store;
import com.intermarche.edge.security.FeatureAccess;
import io.quarkus.qute.Location;
import io.quarkus.qute.Template;
import io.quarkus.qute.TemplateInstance;
import io.quarkus.security.Authenticated;
import jakarta.inject.Inject;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.Consumes;
import jakarta.ws.rs.DefaultValue;
import jakarta.ws.rs.GET;
import jakarta.ws.rs.POST;
import jakarta.ws.rs.Path;
import jakarta.ws.rs.Produces;
import jakarta.ws.rs.QueryParam;
import jakarta.ws.rs.core.MediaType;
import jakarta.ws.rs.core.MultivaluedMap;
import jakarta.ws.rs.core.Response;
import org.jboss.logging.Logger;

import java.security.SecureRandom;
import java.util.HexFormat;
import java.util.List;

/**
 * The THIRD-PARTY SYSTEMS back office ({@code /admin/third-party-systems}) —
 * where the integration activity of the point of sale is configured
 * (BO-07-01-01): each system whose sales the store integrates, its kind
 * (e-commerce or mobility), the point of sale its sales count for, the virtual
 * register they are booked on, whether it may deposit, and the token it
 * presents. A token is generated by the node, never typed, and can be
 * regenerated to cut off a leaked one without touching the other systems.
 */
@Path("/admin/third-party-systems")
public class AdminThirdPartySystemResource {

    /** Technical log of this class. */
    private static final Logger LOGGER = Logger.getLogger(AdminThirdPartySystemResource.class);

    /** The screen's own path. */
    static final String PAGE = "/admin/third-party-systems";

    /** The channels a third-party system may be of. */
    static final List<SalesChannel> CHANNELS = List.of(SalesChannel.ECOMMERCE, SalesChannel.MOBILITY);

    /** The source of the tokens. */
    private static final SecureRandom RANDOM = new SecureRandom();

    /** The page template. */
    @Inject
    @Location("admin-third-party-systems")
    Template adminThirdPartySystems;

    /**
     * Shows the declared systems and the form that declares one.
     *
     * @param notice the one-shot outcome message, or null
     * @param noticeOk whether the message reports a success
     * @return the page
     */
    @GET
    @Authenticated
    @FeatureAccess(value = Feature.THIRD_PARTY_SYSTEM)
    @Produces(MediaType.TEXT_HTML)
    @Transactional
    public TemplateInstance systemsPage(@QueryParam("notice") String notice,
                                        @QueryParam("noticeOk") @DefaultValue("true") boolean noticeOk) {
        LOGGER.info("Entering method systemsPage");
        TemplateInstance page = adminThirdPartySystems.data("systems", ThirdPartySystem.listAllOrdered())
                .data("channels", CHANNELS)
                .data("stores", Store.listAll())
                .data("notice", notice)
                .data("noticeOk", noticeOk);
        LOGGER.info("Exiting method systemsPage");
        return page;
    }

    /**
     * Declares a system or updates it, by its code (BO-07-01-01). A new
     * system receives its token at once.
     *
     * @param form the posted form (code, label, channel, pdvNumber,
     *             terminalId, active)
     * @return a 303 back to the screen
     */
    @POST
    @Path("/save")
    @Authenticated
    @FeatureAccess(value = Feature.THIRD_PARTY_SYSTEM, option = CrudOption.CREATE, updateKey = "code",
            entity = ThirdPartySystem.class)
    @Consumes(MediaType.APPLICATION_FORM_URLENCODED)
    @Transactional
    public Response save(MultivaluedMap<String, String> form) {
        LOGGER.info("Entering method save");
        String code = AdminForms.text(form, "code");
        if (code == null || !code.matches("[A-Za-z0-9_-]{1,40}")) {
            LOGGER.info("Exiting method save: no code");
            return AdminForms.redirect(PAGE, "Code de système tiers invalide.", false);
        }
        String pdvNumber = AdminForms.text(form, "pdvNumber");
        if (pdvNumber != null && Store.find("code", pdvNumber).firstResult() == null) {
            LOGGER.info("Exiting method save: unknown point of sale");
            return AdminForms.redirect(PAGE, "Point de vente inconnu : " + pdvNumber, false);
        }
        ThirdPartySystem existing = ThirdPartySystem.findByCode(code);
        ThirdPartySystem system = existing == null ? new ThirdPartySystem() : existing;
        system.code = code;
        String label = AdminForms.text(form, "label");
        system.label = label == null ? code : label;
        SalesChannel channel = SalesChannel.fromName(AdminForms.text(form, "channel"));
        system.channel = CHANNELS.contains(channel) ? channel : SalesChannel.ECOMMERCE;
        system.pdvNumber = pdvNumber;
        system.terminalId = AdminForms.text(form, "terminalId");
        system.active = AdminForms.checkbox(form, "active");
        if (existing == null) {
            system.token = newToken();
            system.persist();
        }
        LOGGER.info("Exiting method save");
        return AdminForms.redirect(PAGE, existing == null ? "Système tiers déclaré." : "Système tiers enregistré.", true);
    }

    /**
     * Gives a system a new token, the old one refused from now on
     * (BO-07-01-01).
     *
     * @param form the posted form (code)
     * @return a 303 back to the screen
     */
    @POST
    @Path("/token")
    @Authenticated
    @FeatureAccess(value = Feature.THIRD_PARTY_SYSTEM, option = CrudOption.UPDATE)
    @Consumes(MediaType.APPLICATION_FORM_URLENCODED)
    @Transactional
    public Response regenerate(MultivaluedMap<String, String> form) {
        LOGGER.info("Entering method regenerate");
        ThirdPartySystem system = ThirdPartySystem.findByCode(AdminForms.text(form, "code"));
        if (system == null) {
            LOGGER.info("Exiting method regenerate: unknown system");
            return AdminForms.redirect(PAGE, "Système tiers inconnu.", false);
        }
        system.token = newToken();
        LOGGER.info("Exiting method regenerate");
        return AdminForms.redirect(PAGE, "Nouveau jeton généré : l'ancien est refusé.", true);
    }

    /**
     * A new token: 32 random hexadecimal characters.
     *
     * @return the token
     */
    static String newToken() {
        byte[] bytes = new byte[16];
        RANDOM.nextBytes(bytes);
        return HexFormat.of().formatHex(bytes);
    }
}
